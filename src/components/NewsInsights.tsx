import { useMemo } from 'react';
import type { InsightsResponse, Story } from '../../shared/types';
import { useResource } from '../lib/useResource';
import { escapeHtml } from '../lib/format';

/** AI brief of the top stories, with the stories it cites. Shows a neutral note when no AI key is set. */
export function AiBrief() {
  const { data, error, loading, reload } = useResource<InsightsResponse>('/api/insights', 300_000);
  if (loading && !data) return <section className="brief small muted">Writing the brief…</section>;
  if (error && !data) {
    return (
      <section className="brief small">
        <strong>AI brief unavailable.</strong> <button className="btn btn-ghost btn-sm" onClick={reload}>Try again</button>
      </section>
    );
  }
  if (!data || !data.configured) {
    return <section className="brief small muted">{data?.message ?? 'The AI brief is not switched on yet.'}</section>;
  }
  return (
    <section className="brief" aria-label="AI brief">
      <div className="brief-head small">
        <strong>AI brief</strong>
        <span className="muted"> · generated by AI from the headlines below · {data.model}</span>
      </div>
      <p className="brief-text">{data.brief}</p>
      <ol className="brief-sources small">
        {data.sources.slice(0, 8).map((s) => (
          <li key={s.n}>
            <a href={s.link} target="_blank" rel="noopener noreferrer">{s.title}</a>
            <span className="muted"> · {s.outlets} outlet{s.outlets === 1 ? '' : 's'}</span>
          </li>
        ))}
      </ol>
    </section>
  );
}

/** Stories per day for the last 7 days, counted from the headlines we actually have. */
export function StoryTimeline({ stories }: { stories: Story[] }) {
  const days = useMemo(() => {
    const out: { label: string; count: number; critical: number }[] = [];
    const now = new Date();
    for (let i = 6; i >= 0; i--) {
      const d = new Date(now);
      d.setHours(0, 0, 0, 0);
      d.setDate(d.getDate() - i);
      const next = new Date(d);
      next.setDate(next.getDate() + 1);
      const inDay = stories.filter((s) => {
        const t = Date.parse(s.publishedAt);
        return t >= d.getTime() && t < next.getTime();
      });
      out.push({
        label: d.toLocaleDateString([], { weekday: 'short' }),
        count: inDay.length,
        critical: inDay.filter((s) => s.breaking).length,
      });
    }
    return out;
  }, [stories]);
  const max = Math.max(1, ...days.map((d) => d.count));
  return (
    <section className="timeline" aria-label="Stories per day, last 7 days">
      <div className="timeline-head small"><strong>Headlines per day</strong><span className="muted"> · last 7 days, from the feeds we read</span></div>
      <div className="timeline-bars" role="img" aria-label={days.map((d) => `${d.label} ${d.count}`).join(', ')}>
        {days.map((d) => (
          <div key={d.label + d.count} className="timeline-col" title={`${d.label}: ${d.count} headlines${d.critical ? `, ${d.critical} breaking` : ''}`}>
            <div className="timeline-bar" style={{ height: `${Math.round((d.count / max) * 100)}%` }} />
            <span className="timeline-label small muted">{escapeHtml(d.label)}</span>
            <span className="timeline-count small">{d.count}</span>
          </div>
        ))}
      </div>
    </section>
  );
}
